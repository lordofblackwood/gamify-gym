export const BENCHMARKS = Object.freeze(
  groups
    .flatMap(([tier, rows]) =>
      rows.map(
        ([
          id,
          character,
          era,
          form,
          powerLevel,
          sourceId,
          note,
          continuity,
        ]) => {
          const source = sourceId ? SOURCES[sourceId] : null;
          return Object.freeze({
            id,
            character,
            saga: era,
            era,
            form,
            displayName: id === "farmer" ? character : `${character} · ${form}`,
            powerLevel,
            relativePowerValue: powerLevel,
            tier,
            continuity: continuity || "Main story",
            canonicalPowerLevelKnown:
              source?.kind === "stated" || source?.kind === "guide",
            powerLevelKind:
              id === "zeno" || id === "grand-priest"
                ? "symbolic"
                : source?.kind || "estimated",
            sourceId: sourceId || null,
            avatarRef: null,
            description:
              note ||
              `${character} during ${era}. ${source ? "Published battle-power benchmark; comparison to your gym performance is fictional." : "A curated app estimate for this era and form; not an official numerical power level."}`,
          });
        },
      ),
    )
    .sort((a, b) => a.powerLevel - b.powerLevel),
);
export const BENCHMARK_BY_ID = Object.fromEntries(
  BENCHMARKS.map((b) => [b.id, b]),
);
